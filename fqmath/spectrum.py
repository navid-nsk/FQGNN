"""
fqmath.spectrum
===============

The aperiodic spectrum Lambda' of the Fourier quasicrystal, and its variety-FIXED amplitudes.

GEOMETRY (faithful).  AKKV Thm 2.3 (Eq. 2): the spectrum is generated by
        Lambda'(L) = { L^T k : k in Z^n,  var(k) < d } ,
where var(k) is the number of sign changes in the integer vector k after discarding zeros
(AKKV Def. 2.1).  `enumerate_spectrum_combos` builds the integer combos k (truncated by the
||k||_inf <= K radius, deduplicated by +-k to a CANONICAL +-representative); `FQSpectrum.frequencies`
maps them to xi_k = L^T k (differentiable in L).

DENSITY OF THE SPECTRUM.  Lambda' is a finitely-generated Z-module of
Q-rank <= n (= n only under Q-independence of the rows; AKKV Thm 2.6(2)).  It is COUNTABLE and
TOPOLOGICALLY DENSE in R^d -- it is NOT uniformly discrete.  What IS uniformly discrete is the
SUPPORT Lambda(X,L) of the FQ point set.  The FQ measure mu = sum c_xi delta_xi is locally finite
because the AMPLITUDES DECAY (c_xi = O(1/||k||^2) => square-summable), NOT because the spectrum is
u.d.  Consequently the ||k||_inf <= K truncation is a CONTROLLED O(1/K)-tail approximation of a
dense spectrum (LO-Annals Thm 1: a u.d. spectrum with u.d. support would force a periodic crystal).

AMPLITUDES.  The amplitudes are FIXED by the variety (a free learnable amplitude would decouple them
from it):
        d = 1 :  c_k = <ell, k> * c_P(k)              (KS; c_P = log-p_U cumulant, EXACT)
        d >= 2:  c_{L,k} = sum_I L_I * mhat_{[n] minus I}(k)   (AKKV Eq. 9; var(k)=0 part exact)
computed in `fqmath.akkv_amplitudes`.  Amplitudes are COMPLEX with Hermitian symmetry
c_{-k}=conj(c_k) and a support mask 1[|c_k|>0].  A FREE-amplitude mode exists ONLY as the
explicitly-labeled GEOMETRY-ONLY QUASICRYSTAL ABLATION (a baseline), never as faithful FQ.
"""

from __future__ import annotations

import itertools
import os
from typing import List, Tuple

import numpy as np
import torch
import torch.nn as nn

from .akkv_amplitudes import (DEFAULT_AKKV_N_MC, akkv_torus_amplitudes,
                              secular_amplitudes_d1, secular_pullback_amplitudes,
                              support_mask)


def var_sign_changes(k: Tuple[int, ...]) -> int:
    """var(k): number of sign changes in the nonzero entries of k (AKKV Def. 2.1)."""
    s = [int(np.sign(v)) for v in k if v != 0]
    return sum(1 for i in range(1, len(s)) if s[i] != s[i - 1])


def _canonical(k: Tuple[int, ...]) -> Tuple[int, ...]:
    """The canonical +-representative of {k, -k}: the one whose first nonzero entry is positive.
    For var(k)=0 (all same sign) this returns the non-negative vector, which the secular cumulant
    code consumes directly; the conjugate partner c_{-k}=conj(c_k) is handled by Hermitian symmetry."""
    for v in k:
        if v > 0:
            return k
        if v < 0:
            return tuple(-x for x in k)
    return k


def enumerate_spectrum_combos(n: int, d: int, k_max: int, max_freqs: int) -> np.ndarray:
    """
    Integer combos k in Z^n with ||k||_inf <= k_max, var(k) < d, k != 0, deduplicated by +-k to the
    CANONICAL +-representative (`_canonical`), returned as the `max_freqs` smallest-||.||_1 combos,
    int array [M, n].  Rings are filled COMPLETELY (radius by radius) so the kept set is radially
    coherent; the count cap is the O(1/K)-tail budget on a DENSE spectrum (see module docstring).
    """
    combos: List[Tuple[int, ...]] = []
    seen = set()
    for r in range(1, k_max + 1):
        ring = []
        for k in itertools.product(range(-r, r + 1), repeat=n):
            if not any(k):
                continue
            if max(abs(v) for v in k) != r:
                continue
            if var_sign_changes(k) >= d:
                continue
            kc = _canonical(k)
            if kc in seen:
                continue
            seen.add(kc)
            ring.append(kc)
        ring.sort(key=lambda kk: sum(abs(v) for v in kk))
        combos.extend(ring)  # keep whole rings (radial coherence); cap applied after the ring
        if len(combos) >= max_freqs:
            break
    # optional (env FQ_ENUM_RINGS=1): apply the radial coherence at the CAP too —
    # truncate to the largest complete ||k||_1 shell that fits within max_freqs, so the kept set is
    # never an arbitrary generation-order slice of a shell.  Default (unset): the plain
    # combos[:max_freqs] cut (trained checkpoints depend on the kept set AND on M).
    if os.environ.get("FQ_ENUM_RINGS") == "1" and len(combos) > max_freqs:
        norms = [sum(abs(v) for v in kk) for kk in combos]
        # walk back to the start of the ||k||_1 shell that straddles the cap
        cut = max_freqs
        while 0 < cut < len(norms) and norms[cut - 1] == norms[cut]:
            cut -= 1
        combos = combos[:cut] if cut > 0 else combos[:max_freqs]
    else:
        combos = combos[:max_freqs]
    # float32 for the in-graph buffers/einsum of the inline consumers (op_spectral_block,
    # op_coupled_spectral); FQSpectrum derives the integer combos separately for the cumulant code.
    return np.array(combos, dtype=np.float32)  # [M, n]


class FQSpectrum(nn.Module):
    """
    The truncated aperiodic spectrum {xi_k = L^T k} with VARIETY-FIXED complex amplitudes {c_k}.

    Parameters
    ----------
    grassmann : module exposing forward() -> L [n, d] and minors(L) -> [C(n,d)]
    k_max, max_freqs : spectrum truncation radius K and count budget M
    amplitude : "secular"    (variety-FIXED via a secular unitary U: d=1 exact KS cumulants;
                              d=2 the var(k)=0 harmonic sub-comb with the ||L^T k|| weight,
                              beats masked -- the DEFAULT)
                "akkv_torus" (the AKKV Thm 2.6(3) / Eq.-9 torus-integral amplitudes at
                              d=2 on the canonical secular split family -- var(k)=1 beat
                              tones generically LIVE; QMC-computed, non-differentiable,
                              cached per (L, U); see fqmath.akkv_amplitudes)
                "free"       (a learnable amp_w linear in minors -- the GEOMETRY-ONLY
                              ABLATION, labeled)
    secular  : an optional shared fqmath.lee_yang.SecularUnitary providing the variety U; if None and
               amplitude in ("secular", "akkv_torus"), one is constructed internally.

    ENV OVERRIDE: if the environment variable FQ_AMP_MODE is set (non-empty)
    at construction time it overrides `amplitude` -- e.g. FQ_AMP_MODE=akkv_torus switches a
    model whose call sites pass amplitude="secular" into the torus-integral mode
    without changing any call site.  Unset env => the constructor argument is used.
    FQ_AMP_NMC optionally overrides the QMC budget of the akkv_torus mode.
    """

    def __init__(self, grassmann, k_max: int = 3, max_freqs: int = 64, seed: int = 0,
                 amplitude: str = "secular", secular=None):
        super().__init__()
        env_mode = os.environ.get("FQ_AMP_MODE", "").strip()
        if env_mode:
            amplitude = env_mode
        self.grassmann = grassmann
        self.n = grassmann.n
        self.d = grassmann.d
        combos = enumerate_spectrum_combos(self.n, self.d, k_max, max_freqs)
        if combos.shape[0] == 0:
            raise ValueError("empty spectrum; increase k_max / max_freqs")
        self.register_buffer("combos", torch.tensor(combos, dtype=torch.float32))  # [M, n] (signed, canonical)
        self.M = combos.shape[0]
        self._combos_int = [tuple(int(v) for v in row) for row in combos]
        self.amplitude_mode = amplitude
        self.n_minors = len(grassmann.minor_indices())  # C(n, d)
        self._seed = seed
        self._akkv_cache = None      # (L_cpu64, U_cpu128, c_cpu128) -- akkv_torus mode only

        if amplitude in ("secular", "akkv_torus"):
            from .lee_yang import SecularUnitary
            self.secular = secular if secular is not None else SecularUnitary(self.n, coupled=True, seed=seed)
        elif amplitude == "free":
            # GEOMETRY-ONLY ABLATION (NOT faithful FQ): amplitude c_k = sum_I L_I * amp_w, amp_w free.
            g = torch.Generator().manual_seed(seed)
            self.amp_w = nn.Parameter(0.1 * torch.randn(self.n_minors, self.M, generator=g))
        else:
            raise ValueError(
                f"amplitude must be 'secular', 'akkv_torus' or 'free', got {amplitude!r}")

    def frequencies(self, L: torch.Tensor | None = None) -> torch.Tensor:
        """xi_k = L^T k for every combo k. Returns [M, d] (differentiable in L)."""
        if L is None:
            L = self.grassmann.forward()
        return self.combos.to(L.dtype) @ L  # [M, n] @ [n, d] -> [M, d]

    def amplitudes(self, L: torch.Tensor | None = None) -> torch.Tensor:
        """
        VARIETY-FIXED complex amplitudes c_k [M].  amplitude="secular": the KS / AKKV
        amplitude from fqmath.akkv_amplitudes (d=1 exact; d>=2 exact on var(k)=0, masked on beats).
        amplitude="akkv_torus": the Thm-2.6(3)/Eq.-9 torus-integral amplitudes (beats LIVE;
        no support mask is applied -- the mode's amplitudes ARE the support).
        amplitude="free": the labeled geometry-only ablation (real, cast to complex).
        """
        if L is None:
            L = self.grassmann.forward()
        if self.amplitude_mode == "secular":
            U = self.secular.unitary()
            if self.d == 1:
                # combos are canonical (>= 0 for var=0); ell = L[:, 0]
                return secular_amplitudes_d1(L[:, 0], U, self._combos_int)
            c, _mask = secular_pullback_amplitudes(L, U, self._combos_int)
            return c
        if self.amplitude_mode == "akkv_torus":
            # QMC torus-integral amplitudes -- deterministic given self._seed, computed
            # in fp64/complex128 on CPU, non-differentiable (an offline table), cached per
            # exact (L, U) content.  Cast to the secular path's complex dtype on L.device.
            U = self.secular.unitary()
            Lk = L.detach().to("cpu", torch.float64)
            Uk = U.detach().to("cpu", torch.complex128)
            hit = (self._akkv_cache is not None
                   and torch.equal(self._akkv_cache[0], Lk)
                   and torch.equal(self._akkv_cache[1], Uk))
            # FQ_AMP_REFRESH=N (training-time policy, default 0 = exact): tolerate up to N stale
            # forwards before recomputing, so the QMC table is piecewise-constant while (L,U)
            # train (the table is non-differentiable anyway; U's gradient flows through the
            # secular features, not through c).  N=0 keeps the exact per-content cache.
            refresh_n = int(os.environ.get("FQ_AMP_REFRESH", 0))
            if not hit and refresh_n > 0 and self._akkv_cache is not None:
                self._akkv_stale = getattr(self, "_akkv_stale", 0) + 1
                if self._akkv_stale < refresh_n:
                    hit = True                       # serve the stale table (piecewise-constant)
                else:
                    self._akkv_stale = 0
            if not hit:
                n_mc = int(os.environ.get("FQ_AMP_NMC", DEFAULT_AKKV_N_MC))
                c128 = akkv_torus_amplitudes(Lk, Uk, self._combos_int, n_mc=n_mc,
                                             seed=self._seed)
                self._akkv_cache = (Lk, Uk, c128)
            cdt = U.dtype if U.is_complex() else torch.complex64
            return self._akkv_cache[2].to(device=L.device, dtype=cdt)
        # free ablation
        minors = self.grassmann.minors(L)            # [C] real
        return (minors @ self.amp_w).to(torch.complex64)  # [M] complex (Im=0): the ablation

    def support(self, L: torch.Tensor | None = None) -> torch.Tensor:
        """The variety support mask 1[|c_k|>0] -- apply BEFORE Op-D taps so extinct atoms
        (var(k)>=d / vanishing cumulant, AKKV Thm 4.32) are never populated."""
        return support_mask(self.amplitudes(L))

    def forward(self, L: torch.Tensor | None = None) -> Tuple[torch.Tensor, torch.Tensor]:
        if L is None:
            L = self.grassmann.forward()
        return self.frequencies(L), self.amplitudes(L)

    @property
    def out_dim(self) -> int:
        # the spectral transform returns [cos, sin] weighted features over M frequencies
        return 2 * self.M
